				+ startDate + "\n" + "LOCATION:" + "\n"
				+ "SUMMARY;LANGUAGE=en-us:" + companyCode + " - "
				+ calendarType + adjustedSummary + "\n" + "END:VEVENT\n"
				+ "END:VCALENDAR";
		window.open("data:text/calendar;charset=utf8,"
				+ encodeURIComponent(filedata));
