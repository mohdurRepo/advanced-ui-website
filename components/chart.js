  function initializeMarketNewsTabs(component) {
    const tabsRoot = component.querySelector("[data-tabs]");

    if (!tabsRoot) {
      return;
    }

    const tabs = Array.from(
      tabsRoot.querySelectorAll(
        '[role="tab"][data-tab-target]'
      )
    );

    if (!tabs.length) {
      return;
    }

    const panels = tabs
      .map(function (tab) {
        const panelId = tab.getAttribute("data-tab-target");

        if (!panelId) {
          return null;
        }

        return tabsRoot.querySelector(
          "#" + CSS.escape(panelId)
        );
      })
      .filter(Boolean);

    function activateTab(selectedTab, moveFocus) {
      const selectedPanelId =
        selectedTab.getAttribute("data-tab-target");

      tabs.forEach(function (tab) {
        const isActive = tab === selectedTab;

        tab.classList.toggle("active", isActive);
        tab.setAttribute(
          "aria-selected",
          String(isActive)
        );
        tab.setAttribute(
          "tabindex",
          isActive ? "0" : "-1"
        );
      });

      panels.forEach(function (panel) {
        const isActive = panel.id === selectedPanelId;

        panel.classList.toggle("active", isActive);
        panel.setAttribute(
          "aria-hidden",
          String(!isActive)
        );
        panel.hidden = !isActive;
      });

      if (moveFocus) {
        selectedTab.focus();
      }
    }

    tabs.forEach(function (tab, index) {
      tab.addEventListener("click", function () {
        activateTab(tab, false);
      });

      tab.addEventListener("keydown", function (event) {
        let nextIndex = index;

        switch (event.key) {
          case "ArrowRight":
            nextIndex = (index + 1) % tabs.length;
            break;

          case "ArrowLeft":
            nextIndex =
              (index - 1 + tabs.length) % tabs.length;
            break;

          case "Home":
            nextIndex = 0;
            break;

          case "End":
            nextIndex = tabs.length - 1;
            break;

          case "Enter":
          case " ":
            event.preventDefault();
            activateTab(tab, false);
            return;

          default:
            return;
        }

        event.preventDefault();
        activateTab(tabs[nextIndex], true);
      });
    });

    const initialTab =
      tabs.find(function (tab) {
        return (
          tab.getAttribute("aria-selected") === "true"
        );
      }) || tabs[0];

    activateTab(initialTab, false);
  }

